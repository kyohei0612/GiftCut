/**
 * **他と同時に回してはいけない章。いまは空。**
 *
 * ## 最初は3章を外していた。**測ったら要らなかった**（2026-08-05）
 *
 * 時間を測る章（`12-プレビュー` の絵の止まり、`17-目と耳の確認` の画素と音、
 * `03-音と書き出し`）は、隣で別の Electron が CPU を使うと数字が狂うはずだと考えて
 * 1つずつ回していた。このリポジトリには実際、別のセッションが Electron を
 * 起動しただけで**6項目が同時に赤**になった記録がある。
 *
 * **ところが、括りが大雑把だった。** 全部並列にして4回回したら、
 * **4回とも 290/0・4.2分**でぶれなかった（件数も全章が基準どおり）。
 *
 * ```
 * 3章を外す   7.3分（うち 4.3分が「1つずつ」の待ち）
 * 全部並列    **4.2分**
 * ```
 *
 * 1回の緑では決めていない——`絵が止まらない` は**直列でも間欠的に赤**になった
 * 実績があるので、1回通っただけでは「たまたま」と区別が付かない。
 *
 * ## 戻すときは、章名を1つ足すだけ
 *
 * ここが空でも仕組みは生きている。間欠的に赤くなる章が出たら、
 * **その章名だけ**を書けば1つずつに戻る（`GIFTCUT_SERIAL_ONLY=` で試せる）。
 *
 * **速さのために正しさを捨てない**、は変えていない。
 * 変えたのは「どれが本当に静かな窓を要るか」を、推測から実測にしたこと。
 */
