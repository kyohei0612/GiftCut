// 負荷チェックの**時間まわり**。「その回は信じていいか」と「何に時間を食ったか」。
//
// ## なぜ要るか（2026-08-07）
//
// どちらも**今日1日、私が繰り返し詰まった所**をそのまま道具にした物。
//
// ## 中身
//
// - `素の重さを測る` … 触る前に、何もしていないときのコマ間隔を測る
// - `周りを測る` … **項目1つ1つの前後**で、そのとき周りが何をしていたかを控える
// - `時計を作る` … 段ごとの時間を控えて、最後に長い順で出す

/**
 * 触らずに `ms` ぶんのコマ間隔を数え、中央値を返す。
 *
 * **`素の重さを測る` と `周りを測る` の両方がここを通る。** 同じ数え方を2か所に
 * 書くと、片方だけ直った日に「起動時 4.2ms・項目ごと 8.0ms」のような、
 * 比べられない2つの数字が並ぶ（このリポジトリで4回起きた型）。
 */
/**
 * これを超えたら「機械が空いていない」。
 * 空のときが 4.2ms（毎秒240コマ相当）なので、その倍を線にしてある。
 */
const 重い線 = 8

/**
 * **決まった量の計算。** 回すたびに同じ仕事量になるよう、中身は固定。
 *
 * ## なぜ「触っていないときのコマ間隔」では足りないのか（2026-08-08）
 *
 * `全部選んでまとめて動かす` が同じコードで3倍に振れる件を、7回回して追った。
 * **悪い回は全項目が揃って悪い**——`50回続けて切る`（映像を一切触らない、
 * 純粋な JS と DOM の仕事）まで **113ms → 168ms** になる。
 * つまり**アプリの仕事が増えたのではなく、機械が出している能力が落ちている。**
 *
 * ところが `素の重さを測る` は、良い回も悪い回も **7回とも 4.2ms** を返した。
 * 理由は単純で、**4.2ms は 240Hz の床**だから。何もしていないときの仕事は
 * 軽すぎて、能力が半分になっても床に収まってしまう。**原理的に見えない。**
 *
 * 床が無い物差しが要る。決まった量を計算させれば、能力が落ちたぶんだけ
 * そのまま時間が伸びる。
 *
 * ※ **画面の中（renderer）で回すこと。** 測りたいのは「この機械」ではなく
 *   「**このアプリの本スレッド**が、いまどれだけ出せるか」。node 側で測ると、
 *   別プロセス・別の優先度の数字になる。
 * ※ 中身に意味は無い（`% 4294967296` は数を 32bit に収めて、
 *   JIT が浮動小数へ逃げないようにしているだけ）。**変えたら過去と比べられない。**
 *
 * ## どこまで動くかは測ってある（＝**何を捕まえられないか**も分かっている）
 *
 * **わざと計算を4本ぶつけて確かめた。** 項目の方は 20良好 → 17良好/3要注意 まで
 * 悪化したのに、この物差しは **24.0 → 26.7ms（+11%）しか動かない。**
 *
 * 理由ははっきりしていて、**詰めた足し算はいちばん取り合いに強い**
 * ——L1 に収まり、1コアで完結するので、他所が忙しくても素通りできる。
 * つまりこれが捕まえるのは「**本スレッドが出せる素の速さ**」であって、
 * 「機械全体が混んでいるか」ではない。
 *
 * ## 記憶側も測ろうとして、**やめた**（作り直さないこと）
 *
 * アプリの仕事は確保と DOM ＝記憶を叩く側なので、16MB の配列を
 * 素数の歩幅（65,537）で 300万回わたる物差しを足してみた。**使えなかった。**
 *
 * ```
 * 1回の中で  記憶 16.6 → 104.4ms（**6倍に散る**）
 * 同じ回の   計算 23.9 →  25.5ms（4%）
 * ```
 *
 * 3回の中央値を取っても収まらない。**散る数字を出すと、次に読む人が
 * 嘘の手掛かりを追う**ので落とした。記憶側を測りたいなら、まず
 * 「なぜ6倍に散るのか」から。
 */
const 物差しの回数 = 3_000_000

/**
 * いまこの本スレッドがどれだけ出せるかを測る（ms・小さいほど速い）。
 *
 * 3回まわして**中央値**を返す。1回目は JIT が温まっていないので必ず遅く、
 * そのまま使うと「1項目目だけ機械が遅い」という嘘になる。
 */
export async function 物差し(page) {
  return page.evaluate((回数) => {
    const ひと回し = () => {
      const t = performance.now()
      let x = 0
      for (let i = 0; i < 回数; i++) x = (x + i * 2654435761) % 4294967296
      // x を捨てると、JIT がループごと消してしまう（0ms になる）
      return { ms: performance.now() - t, x }
    }
    ひと回し() // 温め（捨てる）
    return [ひと回し().ms, ひと回し().ms, ひと回し().ms].sort((a, b) => a - b)[1]
  }, 物差しの回数)
}

async function コマ間隔(page, ms) {
  return page.evaluate(
    (窓) =>
      new Promise((ok) => {
        const 間 = []
        let last = performance.now()
        const t0 = last
        const tick = (t) => {
          間.push(t - last)
          last = t
          if (t - t0 < 窓) requestAnimationFrame(tick)
          else {
            間.sort((a, b) => a - b)
            ok({ 中央: 間[Math.floor(間.length / 2)] ?? 0, 数: 間.length })
          }
        }
        requestAnimationFrame(tick)
      }),
    ms
  )
}

/**
 * **測る前に「何もしていないとき」を測る。**
 *
 * この道具の数字は、**機械が他に取られているかどうかで2倍変わる**。
 * 今日それで何度も惑わされた——同じコードで横スクロールが 20.8ms と 50.0ms、
 * 全項目が同時に悪化し、所要も 9.0秒 → 15.0秒 に伸びていた（chrome が1コア分）。
 * **アプリは無罪だった。**
 *
 * 触らずに2秒ぶんのコマを数えれば、その回が使い物になるか**先に**分かる。
 * 何もしていないのに 4.2ms（毎秒240コマ相当）から離れているなら、
 * そのあとの数字は**アプリのせいではない**。
 *
 * ※ **止めない。** 測れないと決めつけるのはこちらの仕事ではないので、
 *   数字を出して読む人に渡す（自動で捨てると、**本物の悪化まで消える**）。
 */
export async function 素の重さを測る(page, fmt) {
  const 素 = await コマ間隔(page, 2000)
  const 取られている = 素.中央 > 重い線
  console.log(
    (取られている ? '[33m' : '[90m') +
      `  何もしていないときのコマ間隔: 中央値 ${fmt(素.中央)}ms（${素.数}コマ）` +
      (取られている
        ? ' ← **機械が他に取られている。この回の数字はアプリのせいとは限らない**'
        : '') +
      '[0m'
  )
  // **この回の代表値。** 上の行は床（4.2ms）に張り付いて動かないので、
  // 「その回を信じていいか」に本当に答えるのはこちら（理由は `物差し`）
  const 能力 = await 物差し(page)
  console.log(
    `\x1b[90m  決まった量の計算にかかる時間（物差し）: ${fmt(能力)}ms\x1b[0m`
  )
  return { ...素, 取られている, 能力 }
}

/**
 * **項目1つ1つの前後で、そのとき周りが何をしていたかを控える。**
 *
 * ## なぜ起動時の1回では足りないか（2026-08-08）
 *
 * `全部選んでまとめて動かす` が、**同じコードで3倍に振れていた**:
 *
 * ```
 * 20.8ms / 引っかかり  3回 / 8.3秒間   ← 20良好0問題の回
 * 62.3ms / 引っかかり 84回 / 11.6秒間  ← 13良好5要注意2問題の回
 * ```
 *
 * **どちらも起動時の素の重さは 4.2ms**（＝機械は空いている）だった。
 * `src` は1行も触っていない。つまり **起動直後の1回では捕まえられない負荷が、
 * 後から効いてくる**。あれは「その回を信じていいか」には答えるが、
 * 「**その項目**を信じていいか」には答えない。
 *
 * ## 何を控えるか
 *
 * - **周りの重さ** … 触っていないときのコマ間隔。項目の直前と直後の2回
 * - **最適化の進み** … プレビュー最適化（プロキシ作り）の %。**いちばんの容疑者**
 *   （20秒再生の時点で、良い回は 36→47%、悪い回は 67→89% と進み方が違った）。
 *   札が消えていれば `null`＝もう焼き終わっている、という意味になる
 * - **まとめの進み** … 素材ごとまとめの %。これも裏で CPU を食う
 *
 * ※ **`.proxy-badge` は2つある**（`PreviewOverlays` の `ProgressBadges`）。
 *   `querySelector` で先頭を取ると、最適化が終わった後は**まとめの数字が
 *   「最適化」の顔をして出る**。名前が違う物を1つの数字に混ぜると、
 *   次に読む人が別の犯人を追いかけることになるので、文言で分ける。
 *
 * ※ **止めない**（`素の重さを測る` と同じ）。数字を並べて読む人に渡すだけ。
 *   自動で捨てると本物の悪化まで消える。
 */
export async function 周りを測る(page) {
  const 素 = await コマ間隔(page, 600)
  const 札 = await page.evaluate(() =>
    [...document.querySelectorAll('.proxy-badge')].map((el) => el.textContent?.trim() ?? '')
  )
  const 拾う = (語) => {
    const t = 札.find((s) => s.includes(語))
    const m = t && /(\d+)%/.exec(t)
    return m ? +m[1] : null
  }
  return {
    重さ: 素.中央,
    重い: 素.中央 > 重い線,
    能力: await 物差し(page),
    最適化: 拾う('最適化'),
    まとめ: 拾う('まとめ')
  }
}

/**
 * **裏の焼き直しが終わるまで待つ**（`--wait-proxy` のときだけ）。
 *
 * ## なぜ要るか（2026-08-08）
 *
 * `周りを測る` を入れて分かったのは、**周りの重さでは捕まらない**ということ
 * だった——プロキシが 6% → 64% と進んでいる間、触っていないときのコマ間隔は
 * **1項目の例外もなく 4.2ms のまま**。焼き直しは別プロセス（ffmpeg）なので、
 * 手が空いている本スレッドの rAF には出ない。**出るのは本スレッドが実際に
 * 仕事をしている最中だけ**なので、素の重さでは原理的に見えない。
 *
 * 残ったのは相関だけ（最適化の進み方が、良い回と悪い回で違う）。
 * **相関を因果にするには、焼き直しを止めて同じ物を測るしかない。**
 * それがこの口。`npm run bench` と `npm run bench -- --wait-proxy` を
 * 突き合わせる。
 *
 * ※ 待ちきれなくても**止めない**。項目ごとの行に最適化%が出るので、
 *   待てていない回は**読めば分かる**（黙って「待った」ことにはならない）。
 */
export async function 焼き終わるまで待つ(page, 頭打ち分 = 15) {
  const t0 = Date.now()
  const 限 = 頭打ち分 * 60000
  let 言った = false
  while (Date.now() - t0 < 限) {
    const 数 = await page.locator('.proxy-badge').count()
    if (数 === 0) {
      // **1回消えただけでは終わりではない。** 素材ごとに札が出たり消えたりするので、
      // 1秒おいてもう一度見る（`stutter.mjs` の waitQuiet と同じ判断）
      await page.waitForTimeout(1000)
      if ((await page.locator('.proxy-badge').count()) === 0) {
        const 秒 = (Date.now() - t0) / 1000
        console.log(`[90m  裏の焼き直しが終わるまで ${秒.toFixed(1)}秒 待った[0m`)
        return { 終わった: true, 秒 }
      }
    } else if (!言った) {
      言った = true
      console.log('[90m  裏の焼き直し（プレビュー最適化）の完了を待っています…[0m')
    }
    await page.waitForTimeout(1000)
  }
  console.log(
    `[33m  **${頭打ち分}分待っても焼き直しが終わらなかった。** ` +
      'この回は「待てていない」——各項目の行に出る最適化%を見ること[0m'
  )
  return { 終わった: false, 秒: (Date.now() - t0) / 1000 }
}

/**
 * 項目の前後で控えた物を、1行に畳む。**片方でも重ければ、そう言う。**
 *
 * ここを `benchMeasure` 側に書かないのは、**読み方（何を重いと呼ぶか）を
 * 測り方と同じ場所に置いておくため**。線を動かした日に、文言だけ古くなる。
 */
export function 周りを書く(前, 後, fmt) {
  const 札 = (名, 鍵) => {
    if (前[鍵] == null && 後[鍵] == null) return '' // 走っていない仕事は書かない
    const v = (x) => (x == null ? '—' : `${x}%`)
    return `・${名} ${v(前[鍵])}→${v(後[鍵])}`
  }
  return (
    ` / 周り ${fmt(前.重さ)}→${fmt(後.重さ)}ms` +
    // **物差しがこの行のいちばん大事な数字。** 周りの重さは床（4.2ms）に
    // 張り付いて動かないが、こちらは機械が出せる能力にそのまま比例する。
    `・物差し ${fmt(前.能力)}→${fmt(後.能力)}ms` +
    札('最適化', '最適化') +
    札('まとめ', 'まとめ') +
    (前.重い || 後.重い ? '（**周りが重い。アプリのせいとは限らない**）' : '')
  )
}

/**
 * **どこに時間がかかっているかを、あとから言えるようにする。**
 *
 * 通しは30分以上かかるのに、**内訳を出す物が無かった**。「まだ18%」と聞かれても
 * 何が長いのか答えられない——**測る道具なのに、自分の時間は測っていなかった。**
 *
 * 項目ごとの時間は各行に出ている（`8.9秒間` など）が、それは**触っている間**だけ。
 * 素材づくり・起動・書き出し・限界さがしは**どこにも出ていない**。そこを埋める。
 */
export function 時計を作る() {
  const 区切り = []
  let 前 = Date.now()
  return {
    /** ここまでを1段として控える */
    区切る(名) {
      区切り.push({ 名, 秒: (Date.now() - 前) / 1000 })
      前 = Date.now()
    },
    /**
     * 長い順に出す（0.5秒未満は出さない）。
     *
     * `題` を受けるのは、**限界さがしが同じ物を軸ごとに使うから**（19軸の
     * どれが長いのかが、書かれてから一度も出ていなかった）。作り直さず借りる
     * ——同じ形を2つ持つと、片方だけ直る日が来る（このリポジトリで4回起きた型）。
     */
    出す(fmt, 題 = '時間の内訳') {
      const 合計 = 区切り.reduce((a, b) => a + b.秒, 0)
      console.log(`\n[1m${題}[0m  合計 ${fmt(合計 / 60)}分。長い順:`)
      for (const r of [...区切り].sort((a, b) => b.秒 - a.秒)) {
        if (r.秒 < 0.5) continue
        const 割合 = Math.round((r.秒 / 合計) * 100)
        console.log(`  ${String(fmt(r.秒)).padStart(7)}秒  ${String(割合).padStart(3)}%  ${r.名}`)
      }
    }
  }
}
