import 開き直しと差し替え from './16-仕上げ-1-開き直しと差し替え.mjs'
import 置くと編む from './16-仕上げ-2-置くと編む.mjs'
import 見え方 from './16-仕上げ-3-見え方.mjs'

export default async function (C) {
  const { section, resetProject } = C
  section('仕上げ（残っていた確認）')
  await resetProject()

  await 開き直しと差し替え(C)
  await 置くと編む(C)
  await 見え方(C)
}
