// ## **呼ぶ順は1つも変えていない**
//
// e2e には**手前の項目が残した状態に寄りかかっている確認**がある
// （選ばれている物・再生位置・拡大率・置いた素材）。並べ替えると、アプリは
// 正しいのに赤くなる／本当は壊れているのに緑になる。下の5行は元の1,078行を
// 上から順に切っただけの並びで、**入れ替えてはいけない**。
//
// 各ファイルの頭に「順番の話」を書いてある。特に:
//
//   ・`W`（クリップ1つ＝5秒ぶんの幅）は 02a が章の頭で1回だけ測った物。
//     **測り直すと値が変わる**（途中の確認が拡大率を動かす）ので手渡しする
//   ・`11. トラック（段）` の章の名前を宣言しているのは 02d だけ。
//     02e は宣言せず、**02d の直後に呼ばれる前提**で続きを持っている
import clipMove from './02a-クリップを掴んで動かす.mjs'
import silenceRipple from './02b-無音カットとリップル削除.mjs'
import selectAndKeys from './02c-選ぶ操作とキー操作.mjs'
import trackScroll from './02d-トラックと縦スクロール.mjs'
import laneSize from './02e-帯の細さと段の高さ.mjs'

export default async function (C) {
  // ↓ 元のファイルの並びそのまま。**入れ替えない**（上の「呼ぶ順」を読むこと）
  const { W } = await clipMove(C)
  await silenceRipple(C)
  await selectAndKeys(C)
  await trackScroll(C)
  await laneSize(C, W)
}
