// ## なぜ入口だけ残して中身を出したか（2026-08-04）
//
// 分けた先が1,078行あった。上に並べた7つの章が同居していて、
// **500 を超えると AI は通しで読まず grep に切り替わる**ので、どれを直すか
// 決める前に全部を読む羽目になる。**話題（章）で5つに割った。**
// 行数で機械的に切ってはいない。
