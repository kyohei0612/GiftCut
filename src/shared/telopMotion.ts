// テロップの「動き」の形。
//
// 中身の計算（出入りのアニメと重ねる所）は renderer 側の lib/telopStyle にあるが、
// **形だけはここに置く**。画面を持たない側（プリセットの取り込みなど）からも
// 同じ形を作る必要があるため。renderer を import すると Electron ごと引きずる。

import type { Keys } from './keyframes'

export interface Motion {
  /** 横位置（1080基準px。右が＋） */
  tx?: Keys
  /** 縦位置（1080基準px。下が＋） */
  ty?: Keys
  /** 大きさ（1=そのまま） */
  sc?: Keys
  /** 回転（度） */
  rot?: Keys
  /** 透明度（0..1） */
  op?: Keys
  /**
   * 横だけの拡大（1=そのまま）。Premiere の「スケール(幅)」。
   * **弾む・伸びる演出に要る**（滑り込みながら横に潰れて戻る、が作れない）
   */
  scx?: Keys
  /**
   * 縦だけの拡大（1=そのまま）。Premiere の「スケール(高さ)」。
   * **潰れて伸びる演出に要る**（ビョヨン・落ちる・メビウスはこれが本体）。
   */
  scy?: Keys
  /** 歪曲（度）。斜体と同じ skewX で傾ける。Premiere の「歪曲」 */
  skew?: Keys
  /** 横回転（度・Y軸）。Premiere の基本3D「スウィベル」 */
  roty?: Keys
  /** 縦回転（度・X軸）。基本3D「チルト」 */
  rotx?: Keys
  /** 明るさ（1=そのまま）。ProcAmp の明度 */
  bright?: Keys
  /** ぼかし（px・1080基準）。ガウスぼかし */
  blur?: Keys
  /** 色相の回転（度。0=そのまま）。カラーバランス(HLS) の「色相」 */
  hue?: Keys
  /** 色の反転（0=そのまま、1=完全に反転）。Invert の「元の画像とブレンド」の裏返し */
  inv?: Keys
  /**
   * ブラインド（0=全部見える、1=全部隠れる）。Venetian Blinds の「変換終了」。
   * 縞で覆って、だんだん開いていく演出。
   */
  blind?: Keys
  /**
   * ブラインドの縞1本ぶんの幅（px・1080基準）と向き（度）。
   * **この2つは動かない**（実物でも固定値）ので、印ではなく数で持つ。
   */
  blindW?: number
  blindDir?: number
  /** 切り抜き（各辺 0..1）。タイプライターや「光」系に要る */
  cl?: Keys
  ct?: Keys
  cr?: Keys
  cb?: Keys
  /**
   * 波形ワープの「波紋の高さ」（px・1080基準）。文字を波打たせる量。
   *
   * **SPLITSLIDE 系はこれが本体**（-1888 という極端な値で、文字が横に裂けて
   * 飛んでいくように見える）。無いと、ただの滑り込みになってしまう。
   * ほとんどの演出で最後は 0 に戻る＝終われば元の姿。
   */
  wavH?: Keys
  /** 波形ワープの「波形の幅」（px・1080基準）＝波1つぶんの長さ。小さいほど細かい */
  wavW?: Keys
  /** 波形ワープの「方向」（度）。波の向き。0 のままの物が多い */
  wavDir?: Keys
  /**
   * 波形ワープの「波形の速度」（1秒あたりの周回数）。
   * **これは動かない**（実物でも固定値）ので、印ではなく数で持つ。
   * 0 なら波は止まったまま、正なら流れ続ける（ユラユラ系）。
   */
  wavSpd?: number
  /**
   * ブラー（方向）の「ブラーの長さ」（px・1080基準）。動いた跡を引く量。
   * 0 なら効果なし。
   */
  mbLen?: Keys
  /**
   * ブラー（方向）の「方向」（度）。**43.ブラー方向 はこれが本体**で、
   * 0.27秒のあいだに 45 → -45 → -90 → -135 と振れる。
   * 向きを持たない普通のぼかしで代えると、この演出は別物になる。
   */
  mbDir?: Keys
}

/**
 * **印（キーフレーム）を打てる項目だけ**の名前。
 * blindW / blindDir のような「動かない設定値」を、印を打つ道具に渡さないための型。
 */
export type MotionKeyName = {
  [K in keyof Motion]-?: NonNullable<Motion[K]> extends Keys ? K : never
}[keyof Motion]

/**
 * 取り込んで置いてある動きのプリセット1つ（motion-presets/*.json の要素）。
 *
 * partial には、向こうには付いていたがこちらで持てなかったエフェクトの名前が入る。
 * **黙って捨てない**ため（「取り込んだのに見た目が違う」の原因が、一覧の上で分かる）。
 */
export interface MotionPresetFile {
  name: string
  motion: Motion
  partial?: string[]
  /**
   * 演出が終わるとテロップが見えなくなる物（「_上」のような2枚重ねの上側）。
   * **単体で当てると文字が消える**ので、一覧で先に知らせる。壊れているのではない。
   */
  endsHidden?: boolean
}
