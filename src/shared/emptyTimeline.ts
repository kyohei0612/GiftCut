// **タイムラインが空かどうか。** 空のときは、置いた物を 0秒に付ける。
//
// ## なぜ要るか（2026-08-07・本人の指定）
//
// プレミアは、シーケンスが無い状態で素材を落とすと**必ず 0秒から**入る。
// 落とした横位置は見ない。GiftCut は落とした位置をそのまま時刻にしていたので、
// **まっさらな所へ置いたのに 8.3秒から始まる**ということが起きた。
//
// 本人の言葉:「いっちゃん最初の時で、なにもタイムラインにない状態の時を指す。
// 　たとえばタイムラインにあるやつをすべて消したらその状態になるし、
// 　プロジェクト開始のときもそのルールなら、何かしら落としたら 0秒から配置される
// 　ってだけ。配置されたら今の状態が表示されて、置いた奴はただ 0秒から
// 　くっついた状態で配置されるだけ」
//
// つまり**空のときだけ**の話で、1つでも置いてあれば今までどおり落とした位置。
//
// ## 「空」に素材ビンは数えない
//
// 似た判定が既にある（`hasProjectContent`）が、あちらは**ビンに読み込んだ素材も
// 数える**——保存が要るかを決めるための物なので、それで正しい。
// こちらが見たいのは**タイムラインの上に何かあるか**なので、別物として置く。
// 混ぜると、素材を読み込んだ時点で「空ではない」ことになり、規則が効かなくなる。
//
// ## めじるしは数えない
//
// めじるし（マーカー）だけが打ってある状態は、**帯が1本も無い＝見た目は空**。
// そこへ落とした物が落とした位置から始まると、やはり驚く。

/** タイムラインに載っている物（**置いてある帯だけ**。ビンは含めない） */
export interface TimelineContent {
  /** 本編のカット列 */
  segments: unknown[]
  /** 重ねた動画 */
  vClips: unknown[]
  /** テロップ */
  cues: unknown[]
  /** 効果音・音声 */
  seClips: unknown[]
  /** 画像 */
  imgClips: unknown[]
}

/** タイムラインに帯が1本も無いか */
export function timelineIsEmpty(c: TimelineContent): boolean {
  return (
    c.segments.length === 0 &&
    c.vClips.length === 0 &&
    c.cues.length === 0 &&
    c.seClips.length === 0 &&
    c.imgClips.length === 0
  )
}

/**
 * これから置く物の開始時刻。
 *
 * **空なら 0秒。** そうでなければ、狙った時刻をそのまま返す。
 * 落とす／ダブルクリックで置く／端で受け取る、どの道もここを通す
 * ——通さない道が1つでもあると、「入口によって始まる場所が違う」になる。
 */
export function placeStartSec(want: number, empty: boolean): number {
  return empty ? 0 : want
}
