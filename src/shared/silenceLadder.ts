// 無音のしきい値を、素材に合わせて選ぶ。
//
// ## なぜ要るか
//
// **無音のしきい値は素材で変わる。** 静かな録音なら -35dB でよく黙るが、
// 音楽や環境音が乗っている動画では -35dB に一度も落ちない。
// そうなると「どこも無音でない」ことになり、**合わせる先が1つも取れない**。
//
// 以前は「5個取れたら打ち切り」にしていたが、これが甘すぎた。
// 4分の動画で11個しか取れていないのに合格になり、位置合わせが効かないまま
// 素通ししていた（実測: 喋り出しからのズレが 0.3秒以内に収まったのは 2%）。
//
// **足りているかは、素材の長さに対して見る。** 人が喋る動画なら、
// おおよそ4秒に1回は息継ぎや文の切れ目で黙る。それを下回るなら、
// まだしきい値が厳しすぎる。

/** 厳しい順に試すしきい値（dB） */
export const DB_LADDER = [-35, -30, -25, -20] as const

/**
 * その本数で足りているか。
 *
 * @param n     見つかった無音の数
 * @param total 素材の長さ（秒）
 */
export function enoughSilences(n: number, total: number): boolean {
  // 短い素材で無理な数を求めない（下限5個）
  return n >= Math.max(5, Math.floor(total / 4))
}
