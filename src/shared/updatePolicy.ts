// 更新をいつ当てるか。
//
// **こちらから再起動を促さない**（2026-08-02 に変更）。
//
// 以前は「手が空いていれば5秒後に勝手に再起動する」だった。理屈は通っていたが、
// 使う本人からは「毎回いきなり再起動を迫られる」としか見えない。しかも当時は
// インストーラを対話モードで走らせていたので、**再起動のたびにセットアップの
// 画面が出ていた**（置き場所を選ぶ画面まで毎回）。
//
// 望ましいのは「裏で落とし終えておいて、**自分の都合で閉じて開いたら
// 新しくなっている**」。落とすところまでは今までどおり黙ってやり、
// 当てるのは次に閉じたときにする（当てる処理は黙って走る＝画面は出ない）。
//
// 書き出し中・未保存でも結論は同じなので分岐は要らないが、
// **理由は言い分ける**（「書き出し中だから待っている」と分かる方が親切）。

export interface BusyState {
  /** 未保存の変更があるか */
  dirty: boolean
  /** 書き出し中か */
  exporting: boolean
}

export interface UpdatePlan {
  /**
   * いつ当てるか。**いまは必ず onQuit**（こちらから再起動を促さない）。
   *
   * 'now' を残してあるのは、本人が「今すぐ」を押したときの道が要るため。
   * ここが 'now' を返すことは無い。
   */
  when: 'now' | 'onQuit'
  /** 画面に出す説明。何が起きるのかを、起きる前に伝える */
  message: string
  /** now のとき、再起動までの秒数（0 なら即）。いまは常に 0 */
  countdownSec: number
}

/** 更新の準備ができたときに、どうするかを決める */
export function planUpdate(state: BusyState, version = ''): UpdatePlan {
  const v = version ? `${version} ` : ''
  // 結論はどれも同じ（次に閉じたとき）。**理由だけ言い分ける。**
  const why = state.exporting
    ? '書き出し中なので、'
    : state.dirty
      ? '保存していない変更があるので、'
      : ''
  return {
    when: 'onQuit',
    message: `更新 ${v}を用意しました。${why}次にアプリを閉じたときに新しくなります。`,
    countdownSec: 0
  }
}
