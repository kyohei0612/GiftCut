// テロップが「いま出ているか」。**画面と書き出しで、同じ答えを返す。**
//
// ## なぜ1つに寄せるか
//
// 書き出し側は `overlayEnableExpr`（`shared/filterGraph`）が
// `gte(t,start)*lt(t,end)` を組み立てている。画面側がそれと違う判定を持つと、
// **プレビューでは出ているのに、書き出した動画には無い**という食い違いになる。
// この部門でいちばん怖い型——画面では正常に見えるので、書き出すまで分からない。
//
// ## 先頭のテロップを 0秒 まで引き延ばしていた（2026-08-03 にやめた）
//
// 前は「先頭が 0.5秒 以内から始まるなら、頭の隙間を埋める」ために
// **画面側だけ** 0秒 から出していた。狙いは「再生し始めた瞬間に一瞬なにも無い」
// を消すこと。だが:
//
//   ・**書き出しは引き延ばしていない。** 画面に出ている物が製品に無い
//   ・帯はまだ始まっていないのに文字だけ出るので、**壊れて見える**
//     （本人から「まだ来ていないテロップが動画の頭で出ている」と上がった）
//
// 頭の空きが本当に邪魔なら、**テロップの開始を動かす**のが正しい直し方。
// 画面で嘘をついて隠す物ではない。

/**
 * その時刻に出ているか。
 *
 * **終わりは含めない。** 含めると、隣り合うテロップ（前の終わり＝次の始まり）が
 * 切り替わりの1コマで2枚重なる。書き出し側の `lt(t,end)` と同じ扱い。
 */
export function isCueShowing(start: number, end: number, t: number): boolean {
  return t >= start && t < end
}
