// 最初から入っているテロップの動き。
//
// ## ここの値は、全部こちらで打ったもの
//
// **市販のプリセットから写し取っていない。** 「すべり込む」「揺れる」「弾む」は
// 動きの発想としてありふれているが、引っかかるかどうかは発想ではなく
// **数字をそのまま写したかどうか**で分かれる。横揺れなら印は5つで足りるので、
// こちらで打てば議論の余地自体が無くなる。
//
// 取り込んだ物（motion-presets/*.json）は今までどおり別扱いで、配布物には入らない。
//
// ## 何を並べて、何を並べないか
//
// **並べるのは「動きの種類」だけ。「強め」「速い」「大きく」は作らない。**
// 量の作り分けを並べ始めると一覧が倍々に増えるが、**全部を使う人はいない**。
// 量を変えたい人は、テロップを選んで自分で印を打つ側（モーション）でやる。
// ここは「押せばそれっぽくなる入口」に徹する。
//
// ## 打つときの決まり
//
// **必ず元の姿に戻して終わること。**
//   位置(tx/ty)=0 / 大きさ(sc/scx/scy)=1 / 回転=0 / 透明度(op)=1 / 切り抜き=0
// 戻し忘れると、演出が終わったあともテロップがズレたまま座り続ける。
// ここはテストで固定してある（builtinMotions.test.ts）。
//
// 時刻はクリップの先頭からの秒。長さは 0.3〜0.9 秒に収めてある
// （テロップは出て消えるものなので、長い演出は編集の邪魔になる）。

import type { Keys } from './keyframes'
import type { Motion, MotionPresetFile } from './telopMotion'

/** 印1つ。e を省くと直線でつながる（'ease' は両端がゆっくり） */
const k = (t: number, v: number, e?: 'ease' | 'hold'): Keys[number] =>
  e ? { t, v, e } : { t, v }

/** 出るときの薄さ。ほとんどの動きに付ける（いきなり実体で現れると硬い） */
const fadeIn = (dur: number): Keys => [k(0, 0), k(dur, 1)]

const M = (name: string, motion: Motion): MotionPresetFile => ({ name, motion })

