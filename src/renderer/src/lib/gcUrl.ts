// 手元のファイルを、画面（<video> や <audio>）から読める URL に直す。
//
// ## なぜ独立した1行がここに居るか
//
// これは**どこから呼んでも同じ答えを返す純粋な変換**なのに、以前は App.tsx に
// 置いてあり、プレビュー・ダイアログ・素材の読み書きへ prop や deps として
// 配って回っていた（8か所）。渡す物が1つ増えるたび、間に挟まる部品も
// それを受け取って下へ渡す係になる。**配る価値が無い物は配らない。**
//
// ## なぜ encodeURIComponent をセグメントごとに掛けるか
//
// ファイル名に `#` や `?` が入っていると、URL としてはそこから先が
// フラグメントやクエリと読まれて**ファイルが見つからなくなる**。
// かといって丸ごと encodeURIComponent すると区切りの `/` まで潰れる。
// 区切りで分けてから1つずつ包む。
export function toGcUrl(p: string): string {
  return 'gcfile://media/' + p.replace(/\\/g, '/').split('/').map(encodeURIComponent).join('/')
}
