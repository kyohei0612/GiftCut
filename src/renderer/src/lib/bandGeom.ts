// タイムラインの帯の幅。
//
// ## 1px 引くのが要点
//
// 隣り合うクリップ（前の尻＝次の頭）を、時間どおりの幅で描くと**ぴったり接する**。
// 接した所は「前の帯の右の持ち手」と「次の帯の左の持ち手」が同じ画素に重なり、
// **間を掴んだつもりが、どちらを掴んだのか決まらない**（実際に
// 「隣り合っているテロップの間を調整すると両方反応する」と言われた）。
// 1px 空けておけば、掴んだ側が必ず決まる。
//
// ## 最低幅は種類ごとに違う
//
// 短すぎる帯は掴めない・読めないので下限を置く。ただし
// **下限を大きくすると、その帯は隣に食い込む**（時間より広く描くので）。
// 種類ごとに「読めるいちばん細い幅」が違うので、下限だけ呼ぶ側から渡す。
//
// ※ この式は以前 6か所に書き写されていて、**テロップだけ 1px を引き忘れていた**。

/**
 * @param dur  帯が表す長さ（秒）
 * @param zoom px/秒
 * @param min  これより細くはしない（種類ごとの「読めるいちばん細い幅」）
 */
export function bandWidth(dur: number, zoom: number, min: number): number {
  return Math.max(dur * zoom - 1, min)
}
